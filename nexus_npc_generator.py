#!/usr/bin/env python3
"""
NEXUS NPC GENERATOR
Oyunlar için otonom NPC zekası ve davranış ağacı (Behavior Tree) üretici.
"""
import json
import logging
from pathlib import Path

logging.basicConfig(level=logging.INFO, format="[%(asctime)s] 🤖 NPC-GEN: %(message)s")
logger = logging.getLogger("NPCGenerator")

class NexusNPCGenerator:
    def __init__(self):
        self.output_dir = Path("c:/Users/selam/NEXUS-ONE/nexus_autonomous_factory/npc_logic")
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def generate_npc_intelligence(self, npc_name: str, personality: str):
        """
        Belirli bir NPC için davranış mantığı ve AI scripti üretir.
        """
        logger.info(f"🧠 {npc_name} için yapay zeka tasarlanıyor... (Kişilik: {personality})")
        
        # Behavior Tree Yapısı (Örnek)
        logic = {
            "npc_name": npc_name,
            "personality": personality,
            "states": {
                "IDLE": {"action": "play_animation_idle", "next": "WANDER", "condition": "timer_expired"},
                "WANDER": {"action": "move_to_random_point", "next": "IDLE", "condition": "reached_target"},
                "INTERACT": {"action": "look_at_player", "next": "TALK", "condition": "player_nearby"},
                "TALK": {"action": "generate_dynamic_dialogue", "next": "IDLE", "condition": "dialogue_finished"}
            },
            "ai_engine": "Nexus_Core_Brain_v1"
        }
        
        file_path = self.output_dir / f"{npc_name.lower()}_logic.json"
        with open(file_path, "w", encoding="utf-8") as f:
            json.dump(logic, f, indent=2, ensure_ascii=False)
            
        # C# (Unity) Snippet Üretimi
        csharp_snippet = f"""
using UnityEngine;
public class {npc_name}AI : MonoBehaviour {{
    // Generated by NEXUS-ONE NPC Architect
    public string personality = "{personality}";
    void Update() {{
        if (PlayerInRange()) {{
            Interact();
        }}
    }}
    void Interact() {{
        Debug.Log("{npc_name}: Selam yolcu! " + personality + " biriyim.");
    }}
}}
"""
        with open(self.output_dir / f"{npc_name}AI.cs", "w", encoding="utf-8") as f:
            f.write(csharp_snippet)

        logger.info(f"✅ {npc_name} için hem mantık dosyası hem de Unity C# kodu üretildi.")

if __name__ == "__main__":
    gen = NexusNPCGenerator()
